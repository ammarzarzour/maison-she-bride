const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('seller.html','utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(source,'seller script exists');
const from=source.indexOf('function sellerDraftPreviewData(');
const to=source.indexOf('function showSellerDraftPreview()',from);
assert.ok(from>=0&&to>from,'local-only preview builder exists');
const context=vm.createContext({});
vm.runInContext(source.slice(from,to),context);
const fields={titleAr:' فستان عروس ',titleEn:' Bridal dress ',price:'125.50',stock:'3',categoryValid:true,categoryAr:'فساتين',categoryEn:'Dresses',descAr:'وصف',descEn:'Description'};
const preview=(data,lang)=>vm.runInContext('sellerDraftPreviewData('+JSON.stringify(data)+','+JSON.stringify(lang)+')',context);
assert.equal(preview(fields,'ar').title,'فستان عروس');
assert.equal(preview(fields,'en').title,'Bridal dress');
assert.equal(preview(fields,'en').category,'Dresses');
assert.equal(preview(fields,'ar').price,'125.50');
assert.equal(preview(fields,'ar').stock,3);
for(const bad of [{price:'0'},{price:'Infinity'},{price:'1e3'},{price:' 125'},{price:'12.345'},{price:''},{stock:'-1'},{stock:'1.2'},{stock:'1e2'},{stock:' 3'},{stock:''},{stock:'1000001'},{titleAr:'  '},{categoryValid:false}]){
 assert.equal(preview({...fields,...bad},'ar'),null,JSON.stringify(bad));
}
assert.ok(html.includes('id="previewProduct"'));
assert.ok(html.includes('id="productPreview"'));
assert.ok(html.includes('id="hideProductPreview"'));
assert.ok(source.includes("$('hideProductPreview').addEventListener('click'"),'preview can be dismissed');
assert.ok(source.includes("sellerDraftPreviewVisible=false;releaseSellerPreviewImage();$('productPreview').replaceChildren()"),'dismissal clears content and state');
assert.ok(source.includes('"hidePreview":"إخفاء المعاينة"'),'Arabic hide label');
assert.ok(source.includes('"hidePreview":"Hide preview"'),'English hide label');
assert.ok(source.includes("target.replaceChildren()"),'preview must render as DOM text');
assert.ok(source.includes('line.textContent=value'),'untrusted draft fields must never use HTML');
assert.ok(!source.slice(from,source.indexOf("$('productForm').onsubmit",from)).includes('request('),'preview must not write to API');
assert.ok(!source.slice(from,source.indexOf("$('productForm').onsubmit",from)).includes('fetch('),'preview must not upload');
assert.ok(source.includes("if(sellerDraftPreviewVisible)showSellerDraftPreview();"),'preview must follow locale');
assert.ok(source.includes("$('productForm').addEventListener('input'"),'preview updates after edits');
assert.ok(source.includes("$('productForm').addEventListener('change'"),'preview updates after select changes');
assert.ok(source.includes("for(const id of ['titleAr','titleEn','price','stock','descAr','descEn','photo'])$(id).value=''"),'logout must clear all draft fields including image');
assert.ok(source.includes("sellerDraftPreviewVisible=false"),'logout must invalidate preview visibility');
assert.ok(source.includes("$('productPreview').replaceChildren()"),'logout must clear preview contents');
assert.ok(source.includes("categories=[];renderSellerCategories();\n releaseSellerPreviewImage();\n $('productPreview').replaceChildren()"),'category refresh must hide old preview');
assert.ok(source.includes("URL.createObjectURL(photo)"),'photo preview must use local object URL');
assert.ok(source.includes("URL.revokeObjectURL(sellerPreviewImageUrl)"),'object URLs must be revoked');
assert.ok(source.includes("photo.size<=5*1024*1024"),'oversized images must not be previewed');
assert.ok(source.includes("['image/jpeg','image/png','image/webp','image/avif'].includes(photo.type)"),'unsupported images must not be previewed');
assert.ok(source.includes("warning.textContent=tr('previewImageInvalid')"),'invalid images must display localized warning');
assert.ok(source.includes('"previewImageInvalid":"تعذّر عرض الصورة:'),'Arabic invalid image warning');
assert.ok(source.includes('"previewImageInvalid":"Image cannot be previewed:'),'English invalid image warning');
assert.ok(source.includes("img.alt=data.title"),'preview photo needs translated alt text');
assert.ok(source.includes("sellerDraftPreviewVisible=false;releaseSellerPreviewImage();"),'logout must release image');
console.log('PASS bilingual local-only seller draft preview validation and safe rendering');
