const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('seller.html','utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(source);
const start=source.indexOf('function sellerDraftPreviewData(');
const end=source.indexOf('let sellerPreviewImageUrl=',start);
const exportStart=source.indexOf('function sellerDraftExportRecord(');
const exportEnd=source.indexOf("$('downloadProductDraft').addEventListener",exportStart);
assert.ok(start>=0&&end>start&&exportStart>=0&&exportEnd>exportStart);
const ctx=vm.createContext({});
vm.runInContext(source.slice(start,end)+'\n'+source.slice(exportStart,exportEnd),ctx);
const fields={titleAr:' فستان ',titleEn:' Dress ',descAr:'وصف',descEn:'Description',price:'75.25',stock:'4',categoryId:'demo-category'};
const exportDraft=fields=>vm.runInContext('sellerDraftExportRecord('+JSON.stringify(fields)+')',ctx);
const d=exportDraft(fields);
assert.equal(d.title_ar,'فستان');assert.equal(d.title_en,'Dress');
assert.equal(d.price_usd,'75.25');assert.equal(d.stock,4);
assert.equal(d.status,'draft');assert.equal(d.version,1);
assert.equal(d.category_id,'demo-category');
assert.ok(!('image' in d)&&!('user_id' in d)&&!('customer' in d));
for(const bad of [{price:'0'},{price:'1e4'},{stock:'-1'},{stock:'1.5'},{categoryId:null},{titleEn:' '}])assert.equal(exportDraft({...fields,...bad}),null);
assert.ok(html.includes('id="downloadProductDraft"'));
assert.ok(source.includes("anchor.download='maison-she-bride-draft.json'"));
assert.ok(source.includes('JSON.stringify(draft,null,2)'));
assert.ok(source.includes('URL.revokeObjectURL(url)'));
const handler=source.slice(exportEnd,source.indexOf("$('previewProduct').addEventListener",exportEnd));
assert.ok(!handler.includes('fetch(')&&!handler.includes('request('),'no API writes or uploads');
assert.ok(html.includes('"downloadDraft":"تنزيل مسودة JSON"'));
assert.ok(html.includes('"downloadDraft":"Download draft JSON"'));
console.log('PASS validated offline bilingual seller draft JSON export');
